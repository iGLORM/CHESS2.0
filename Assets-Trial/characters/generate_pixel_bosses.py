INK = '#151527'

def begin():
    global im, d
    im = Image.new('RGBA', (96, 112))
    d = ImageDraw.Draw(im)

def p(points, fill, outline=INK, width=2):
    d.polygon(points, fill=fill)
    if outline:
        d.line(points + [points[0]], fill=outline, width=width)

def r(box, fill, outline=None, width=1):
    d.rectangle(box, fill=fill, outline=outline, width=width)

def line(points, fill, width=1):
    d.line(points, fill=fill, width=width)

def gem(x,y,c='#73efe3'):
    p([(x,y-4),(x+3,y),(x,y+4),(x-3,y)],c,width=1)
    r((x-1,y-2,x,y-1),'#e6ffdb')

records=[]
def save(name, title, concept):
    path=OUT/(name+'.png')
    im.save(path)
